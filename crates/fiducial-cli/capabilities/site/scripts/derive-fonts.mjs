// design-system.md (fid:type)  →  apps/web/src/generated/fonts.ts
//
// One `next/font/google` call per type role, bound to the `--face-<role>`
// variable the design tokens already read first in each stack. A role that
// declares its own `var` is loaded by the product and is left alone here.
import { readFileSync, writeFileSync } from "node:fs";

const at = (p) => new URL(`../${p}`, import.meta.url);
const md = readFileSync(at("design-system.md"), "utf8");
// `[site] fonts`: "google" (the default) or "none". Read with a line match:
// one key, and this script must not depend on a TOML reader another
// capability installs.
const config = readFileSync(at("fiducial.toml"), "utf8");
const source = config.match(/^\[site\][^[]*?^fonts\s*=\s*"([^"]*)"/ms)?.[1] ?? "google";
if (!["google", "none"].includes(source)) {
  throw new Error(`[site] fonts = "${source}" is not one of: google, none`);
}
const block = md.match(/```toml fid:type\n([\s\S]*?)```/)?.[1];
if (!block) throw new Error("design-system.md has no `fid:type` block");

const ROLES = ["display", "body", "script", "mono"];
const roles = [];
for (const line of block.split("\n")) {
  const m = line.match(/^(\w+)\s*=\s*\{(.*)\}\s*$/);
  if (!m || !ROLES.includes(m[1])) continue;
  const family = m[2].match(/family\s*=\s*"([^"]+)"/)?.[1];
  const weights = (m[2].match(/weights\s*=\s*\[([^\]]*)\]/)?.[1] ?? "")
    .split(",")
    .map((w) => w.trim())
    .filter(Boolean);
  if (!family) throw new Error(`fid:type role \`${m[1]}\` has no family`);
  if (/\bvar\s*=/.test(m[2])) continue; // loaded by the product
  if (source === "none") continue;
  roles.push({ role: m[1], family, weights });
}

// "Source Serif 4" is exported by next/font/google as `Source_Serif_4`.
const exportName = (family) => family.replace(/[^A-Za-z0-9]+/g, "_");
const imports = [...new Set(roles.map((r) => exportName(r.family)))].sort();

const calls = roles.map(
  (r) =>
    `const ${r.role} = ${exportName(r.family)}({\n  // latin-ext for the letters of Serbian Latin and most European languages.\n  subsets: ["latin", "latin-ext"],\n${r.weights.length ? `  weight: ${JSON.stringify(r.weights)},\n` : ""}  variable: "--face-${r.role}",\n  display: "swap",\n});`,
);

const ts = `// Generated by \`fid derive\` (pipeline: site-fonts) from design-system.md.
// Do not edit — change the \`fid:type\` block and re-derive.
//
// next/font downloads these at build time and serves them from this site.
${imports.length ? `import { ${imports.join(", ")} } from "next/font/google";\n` : ""}
${calls.join("\n\n")}

/** On <html>: binds every \`--face-*\` variable the design tokens read. */
export const fontVariables = ${roles.length ? `[${roles.map((r) => `${r.role}.variable`).join(", ")}].join(" ")` : '""'};
`;
writeFileSync(at("apps/web/src/generated/fonts.ts"), ts);
console.log(`wrote apps/web/src/generated/fonts.ts (${roles.length} role(s))`);
