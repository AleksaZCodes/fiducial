// messages/<locale>.json (`locale.region`)  →  apps/web/src/generated/flags.ts
//
// Named imports of only the declared regions' flags, as SVG strings: the one
// form both pickers (React and Svelte) can draw, and one a bundler tree-shakes.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";

const at = (p) => new URL(`../${p}`, import.meta.url);
const regions = new Set();
for (const file of readdirSync(at("messages"))
  .filter((f) => f.endsWith(".json"))
  .sort()) {
  const catalog = JSON.parse(readFileSync(at(`messages/${file}`), "utf8"));
  const region = catalog?.locale?.region;
  // A flag export is a two-letter region code; anything else draws no flag,
  // which the picker treats as decoration missing rather than an error.
  if (typeof region === "string" && /^[A-Z]{2}$/.test(region)) regions.add(region);
}
const list = [...regions].sort();

const ts = `// Generated by \`fid derive\` (pipeline: i18n-flags) from messages/*.json.
// Do not edit — a locale's flag is its catalog's \`locale.region\`.
//
// Only these flags are bundled: named imports, not the whole set.
${list.length ? `import { ${list.join(", ")} } from "country-flag-icons/string/3x2";\n` : ""}
/** Each declared region's flag, as an SVG string. */
export const flags: Readonly<Record<string, string | undefined>> = { ${list.join(", ")} };
`;
mkdirSync(at("apps/web/src/generated"), { recursive: true });
writeFileSync(at("apps/web/src/generated/flags.ts"), ts);
console.log(`wrote apps/web/src/generated/flags.ts (${list.length} flag(s))`);
