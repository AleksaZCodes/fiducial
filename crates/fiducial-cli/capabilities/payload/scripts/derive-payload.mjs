// fiducial.toml [i18n] + [brand]  →  apps/web/src/generated/payload.ts
//
// Locales, default locale, admin language fallback, entity name, and the role
// union — derived from the declarations, never typed a second time.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const at = (p) => new URL(`../${p}`, import.meta.url);
const read = (p) => readFileSync(at(p), "utf8");

// ── TOML parser (subset: tables, strings, booleans, inline arrays, multiline
// arrays) ──────────────────────────────────────────────────────────────────────

const balanced = (s) => {
  let depth = 0;
  let inStr = false;
  for (let i = 0; i < s.length; i++) {
    const c = s[i];
    if (c === '"' && s[i - 1] !== "\\") inStr = !inStr;
    if (inStr) continue;
    if (c === "[") depth++;
    if (c === "]") depth--;
    if (c === "#") break;
  }
  return depth <= 0;
};

function stripComment(s) {
  let inStr = false;
  for (let i = 0; i < s.length; i++) {
    if (s[i] === '"' && s[i - 1] !== "\\") inStr = !inStr;
    if (s[i] === "#" && !inStr) return s.slice(0, i);
  }
  return s;
}

function parseValue(raw) {
  const v = stripComment(raw).trim();
  if (v.startsWith("[")) {
    const inner = v.slice(1, v.lastIndexOf("]"));
    const items = [];
    let buf = "";
    let depth = 0;
    let inStr = false;
    for (let i = 0; i < inner.length; i++) {
      const c = inner[i];
      if (c === '"' && inner[i - 1] !== "\\") inStr = !inStr;
      if (!inStr) {
        if (c === "[" || c === "{") depth++;
        if (c === "]" || c === "}") depth--;
        if (c === "," && depth === 0) {
          if (buf.trim()) items.push(parseValue(buf));
          buf = "";
          continue;
        }
      }
      buf += c;
    }
    if (buf.trim()) items.push(parseValue(buf));
    return items;
  }
  if (v.startsWith('"')) return v.slice(1, v.lastIndexOf('"')).replace(/\\"/g, '"');
  if (v === "true") return true;
  if (v === "false") return false;
  if (/^-?\d+(\.\d+)?$/.test(v)) return Number(v);
  return v;
}

function parseToml(src) {
  const root = {};
  let table = root;
  let pending = null;

  for (const raw of src.split("\n")) {
    const line = raw.trim();
    if (pending) {
      pending.buf += ` ${line}`;
      if (balanced(pending.buf)) {
        table[pending.key] = parseValue(pending.buf);
        pending = null;
      }
      continue;
    }
    if (!line || line.startsWith("#")) continue;
    const header = line.match(/^\[([^[\]]+)\]$/);
    if (header) {
      table = root;
      for (const part of header[1].split(".")) {
        const key = part.trim().replace(/^"|"$/g, "");
        table[key] ??= {};
        table = table[key];
      }
      continue;
    }
    const kv = raw.match(/^\s*("?[A-Za-z_][\w.-]*"?)\s*=\s*(.*)$/);
    if (!kv) continue;
    const key = kv[1].replace(/^"|"$/g, "");
    const value = kv[2].trim();
    if (!balanced(value)) {
      pending = { key, buf: value };
      continue;
    }
    table[key] = parseValue(value);
  }
  return root;
}

// ── Main ──────────────────────────────────────────────────────────────────────

const cfg = parseToml(read("fiducial.toml"));
const i18n = cfg.i18n ?? {};
const brand = cfg.brand ?? {};

const locales = Array.isArray(i18n.locales) ? i18n.locales : ["en"];
const defaultLocale = i18n.default ?? locales[0] ?? "en";
const entityName = brand.trading_name ?? brand.legal_name ?? "Site";

const PAYLOAD_LOCALES = new Set([
  "ar","az","bg","bnBd","bnIn","ca","cs","da","de","en","es","fa","fr",
  "hr","hu","it","ja","ko","my","nb","nl","pl","pt","ro","rs","ru","sv",
  "th","tr","ua","vi","zh","zhTw",
]);
const adminLocale = PAYLOAD_LOCALES.has(defaultLocale) ? defaultLocale : "en";

const localeEntries = locales.map((code) => {
  let catalog = {};
  try {
    catalog = JSON.parse(read(`messages/${code}.json`));
  } catch {
    // message file may not exist yet — label defaults to the code
  }
  const label = catalog?.locale?.name ?? catalog?.locale?.label ?? code.toUpperCase();
  return { code, label };
});

const ts = `// Generated by \`fid derive\` (pipeline: payload) from fiducial.toml.
// Do not edit — change [i18n] or [brand] and run \`fid derive\`.

export interface PayloadLocale {
  code: string;
  label: string;
}

export const payloadLocales: PayloadLocale[] = ${JSON.stringify(localeEntries, null, 2)};

export const defaultLocale = ${JSON.stringify(defaultLocale)};

export const adminLocale = ${JSON.stringify(adminLocale)};

export const entityName = ${JSON.stringify(entityName)};

export type PayloadRole = "owner" | "staff" | "agency-admin";

export const PAYLOAD_ROLES: PayloadRole[] = ["owner", "staff", "agency-admin"];
`;

mkdirSync(at("apps/web/src/generated"), { recursive: true });
writeFileSync(at("apps/web/src/generated/payload.ts"), ts);
console.log(
  `wrote apps/web/src/generated/payload.ts (${localeEntries.length} locale(s), entity: ${entityName})`
);
