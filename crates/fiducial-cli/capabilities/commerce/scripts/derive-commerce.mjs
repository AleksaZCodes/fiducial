// fiducial.toml [commerce]  →  apps/web/src/generated/commerce.ts
//
// Statuses, lead sources, currency, and cart flag — derived from the
// declaration, never typed a second time.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const at = (p) => new URL(`../${p}`, import.meta.url);
const read = (p) => readFileSync(at(p), "utf8");

// ── TOML parser (subset — shared with derive-payload.mjs) ────────────────────

const balanced = (s) => {
  let depth = 0;
  let inStr = false;
  for (let i = 0; i < s.length; i++) {
    const c = s[i];
    if (c === '"' && s[i - 1] !== "\\") inStr = !inStr;
    if (inStr) continue;
    if (c === "[") depth++;
    if (c === "]") depth--;
    if (c === "#") break;
  }
  return depth <= 0;
};

function stripComment(s) {
  let inStr = false;
  for (let i = 0; i < s.length; i++) {
    if (s[i] === '"' && s[i - 1] !== "\\") inStr = !inStr;
    if (s[i] === "#" && !inStr) return s.slice(0, i);
  }
  return s;
}

function parseValue(raw) {
  const v = stripComment(raw).trim();
  if (v.startsWith("[")) {
    const inner = v.slice(1, v.lastIndexOf("]"));
    const items = [];
    let buf = "";
    let depth = 0;
    let inStr = false;
    for (let i = 0; i < inner.length; i++) {
      const c = inner[i];
      if (c === '"' && inner[i - 1] !== "\\") inStr = !inStr;
      if (!inStr) {
        if (c === "[" || c === "{") depth++;
        if (c === "]" || c === "}") depth--;
        if (c === "," && depth === 0) {
          if (buf.trim()) items.push(parseValue(buf));
          buf = "";
          continue;
        }
      }
      buf += c;
    }
    if (buf.trim()) items.push(parseValue(buf));
    return items;
  }
  if (v.startsWith('"')) return v.slice(1, v.lastIndexOf('"')).replace(/\\"/g, '"');
  if (v === "true") return true;
  if (v === "false") return false;
  if (/^-?\d+(\.\d+)?$/.test(v)) return Number(v);
  return v;
}

function parseToml(src) {
  const root = {};
  let table = root;
  let pending = null;

  for (const raw of src.split("\n")) {
    const line = raw.trim();
    if (pending) {
      pending.buf += ` ${line}`;
      if (balanced(pending.buf)) {
        table[pending.key] = parseValue(pending.buf);
        pending = null;
      }
      continue;
    }
    if (!line || line.startsWith("#")) continue;
    const header = line.match(/^\[([^[\]]+)\]$/);
    if (header) {
      table = root;
      for (const part of header[1].split(".")) {
        const key = part.trim().replace(/^"|"$/g, "");
        table[key] ??= {};
        table = table[key];
      }
      continue;
    }
    const kv = raw.match(/^\s*("?[A-Za-z_][\w.-]*"?)\s*=\s*(.*)$/);
    if (!kv) continue;
    const key = kv[1].replace(/^"|"$/g, "");
    const value = kv[2].trim();
    if (!balanced(value)) {
      pending = { key, buf: value };
      continue;
    }
    table[key] = parseValue(value);
  }
  return root;
}

// ── Main ──────────────────────────────────────────────────────────────────────

const cfg = parseToml(read("fiducial.toml"));
const commerce = cfg.commerce ?? {};

const currency = typeof commerce.currency === "string" ? commerce.currency : "RSD";
const cartEnabled = commerce.cart === true;
const statuses = Array.isArray(commerce.statuses)
  ? commerce.statuses
  : ["new", "quoted", "confirmed", "paid", "delivered", "cancelled"];
const leadSources = Array.isArray(commerce.lead_sources)
  ? commerce.lead_sources
  : ["direct", "instagram", "facebook", "referral", "other"];

const ts = `// Generated by \`fid derive\` (pipeline: commerce) from fiducial.toml.
// Do not edit — change [commerce] and run \`fid derive\`.

export const COMMERCE_CURRENCY = ${JSON.stringify(currency)};

export const COMMERCE_CART_ENABLED = ${cartEnabled};

export const COMMERCE_STATUSES = ${JSON.stringify(statuses)} as const;

export type CommerceStatus = (typeof COMMERCE_STATUSES)[number];

export const COMMERCE_LEAD_SOURCES = ${JSON.stringify(leadSources)} as const;

export type CommerceLeadSource = (typeof COMMERCE_LEAD_SOURCES)[number];

export type StatusTimestampKey = \`\${CommerceStatus}At\`;
`;

mkdirSync(at("apps/web/src/generated"), { recursive: true });
writeFileSync(at("apps/web/src/generated/commerce.ts"), ts);
console.log(
  `wrote apps/web/src/generated/commerce.ts (currency: ${currency}, ${statuses.length} statuses, ${leadSources.length} lead sources)`
);
